package com.supratim;

public class operators {
    public static void main(String[] args){
        int a= 111;
        int b= 12;

        int s= a+b;
        int d= a-b;
        int m= a*b;
        int dv= a/b;
        int r= a%b;
        System.out.println(s);
        System.out.println(d);
        System.out.println(m);
        System.out.println(dv);
        System.out.println(r);

        System.out.println(a++);
        System.out.println(a);
        System.out.println(a--);
        System.out.println(a);
        System.out.println(--a);
        System.out.println(++a);
    }
}
